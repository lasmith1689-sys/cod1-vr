#!/usr/bin/env python
"""Generate src/vr_reload_table.inc: measured reload geometry, keyed by the
gun model's vertex count.

The same key the gun landmarks use, for the same reason -- it is the one thing
the runtime can determine at draw time without guessing. Weapons that share a
gun model share a reload profile, which is correct: the magwell is a property
of the mesh.

Where two weapons on one model disagree about the reload CLASS (they do not,
in the shipped data, but nothing guarantees it), the entry is emitted with the
disagreement recorded and the confidence dropped to WEAK -- a profile that is
right for one of two weapons is not a profile.
"""

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

CLS = {"NONE": 0, "MAGAZINE": 1, "INCREMENTAL": 2, "SINGLE_SHOT": 3}
HAND = {"SUPPORT": 0, "TRIGGER": 1, "BOTH": 0, "NONE": 0}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reload", default="docs/weapon_reload.json")
    ap.add_argument("--guns", default="docs/gun_landmarks.json")
    ap.add_argument("--out", default="src/vr_reload_table.inc")
    args = ap.parse_args()

    reload_rows = {r["weapon"]: r
                   for r in json.load(open(args.reload))["weapons"]}
    guns = json.load(open(args.guns))["models"]

    entries = []
    for g in guns:
        rows = [reload_rows[w] for w in g["weapons"] if w in reload_rows]
        if not rows:
            continue
        classes = set(r["reloadClass"]["value"] for r in rows)
        hands = set(r["loadHand"]["value"] for r in rows)
        first = rows[0]
        conflict = len(classes) > 1 or len(hands) > 1

        cls = CLS.get(first["reloadClass"]["value"], 0)
        hand = HAND.get(first["loadHand"]["value"], 0)
        grip = first.get("gripM", {}).get("value")
        zone = first.get("loadZoneM", {}).get("value")

        # extract_reload measures in the TAG_WEAPON frame; the runtime solves
        # the BODY-BONE frame. Convert through the gun table's rigidity-
        # checked tag->body transform so the shipped numbers live in the
        # frame the gesture is actually scored in.
        tib = g.get("tagInBody")
        if tib and tib.get("rigid"):
            a = tib["axis"]     # tag's rows expressed in body frame
            p = tib["posM"]

            def tag_to_body(v):
                return [p[k] + a[0*3+k]*v[0] + a[1*3+k]*v[1] + a[2*3+k]*v[2]
                        for k in range(3)]
            if grip:
                grip = tag_to_body(grip)
            if zone:
                zone = tag_to_body(zone)
        else:
            grip = zone = None   # no rigid bridge: no gesture, honestly

        # A profile without both a firing grip and a loading zone cannot score
        # a gesture, so it is emitted as invalid rather than half-filled.
        valid = 1 if (grip and zone and cls in (1, 2) and not conflict) else 0
        conf = first["reloadClass"]["confidence"]
        if conflict:
            conf = "WEAK"

        entries.append({
            "verts": g["vertexCount"],
            "model": g["gunModel"],
            "weapons": g["weapons"],
            "cls": cls,
            "clsName": first["reloadClass"]["value"],
            "hand": hand,
            "handName": first["loadHand"]["value"],
            "grip": grip or [0.0, 0.0, 0.0],
            "zone": zone or [0.0, 0.0, 0.0],
            "valid": valid,
            "conf": conf,
            "conflict": conflict,
        })

    L = []
    L.append("// GENERATED by tools/gen_reload_table.py -- do not edit by hand.")
    L.append("//")
    L.append("// Reload geometry measured from each weapon's own reload animation")
    L.append("// (tools/extract_reload.py), keyed by the gun model's vertex count --")
    L.append("// the same exact key the gun landmarks use.")
    L.append("//")
    L.append("// firingGripM / loadZoneM are in the gun model's BODY-BONE frame,")
    L.append("// metres (converted from the measured tag_weapon frame through the")
    L.append("// rigidity-checked tag->body transform in gun_landmarks.json). They are")
    L.append("// where the LOADING hand actually goes in the shipped animation, so a")
    L.append("// Bren's zone is above the receiver and a Thompson's is below it. There")
    L.append("// is no 'magazines are underneath' rule anywhere in this file.")
    L.append("//")
    L.append("// `valid` is 0 for every weapon with no hand reload -- grenades,")
    L.append("// turrets, the panzerfaust -- and for any model whose weapons disagree")
    L.append("// about their reload. An invalid profile makes no gesture at all.")
    L.append("")
    L.append("struct CodvrReloadRow {")
    L.append("    int   vertexCount;")
    L.append("    int   cls;             // VRRL_CLASS_*")
    L.append("    int   hand;            // VRRL_HAND_*")
    L.append("    float firingGripM[3];")
    L.append("    float loadZoneM[3];")
    L.append("    int   valid;")
    L.append("};")
    L.append("")
    L.append("static const CodvrReloadRow kReloadRows[] = {")
    for e in sorted(entries, key=lambda x: x["verts"]):
        L.append("    // %-26s %-12s %-8s %-7s %s"
                 % (e["model"], e["clsName"], e["handName"], e["conf"],
                    ", ".join(e["weapons"][:3])))
        L.append("    { %6d, %d, %d, { %9.5ff, %9.5ff, %9.5ff }, "
                 "{ %9.5ff, %9.5ff, %9.5ff }, %d },"
                 % (e["verts"], e["cls"], e["hand"],
                    e["grip"][0], e["grip"][1], e["grip"][2],
                    e["zone"][0], e["zone"][1], e["zone"][2], e["valid"]))
    L.append("};")

    with open(args.out, "w") as f:
        f.write("\n".join(L) + "\n")

    live = [e for e in entries if e["valid"]]
    print("wrote %s" % args.out)
    print("  models              : %d" % len(entries))
    print("  with a live gesture : %d" % len(live))
    print("  conflicting         : %d" % sum(1 for e in entries if e["conflict"]))
    print()
    print("%-26s %-12s %-8s %-7s %s"
          % ("model", "class", "hand", "valid", "zone (weapon frame, m)"))
    print("-" * 96)
    for e in sorted(entries, key=lambda x: x["model"].lower()):
        print("%-26s %-12s %-8s %-7d [%7.3f %7.3f %7.3f]"
              % (e["model"], e["clsName"], e["handName"], e["valid"],
                 e["zone"][0], e["zone"][1], e["zone"][2]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
