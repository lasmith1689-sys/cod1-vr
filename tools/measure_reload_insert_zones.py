"""Measure reload contact at the weapon's ammo-add event, not hand excursion.

The stock game scales each reload animation to its weapon-file duration.
For receiver loops use the loop itself; for magazine reloads use the empty
reload. Posing the loading hand at ammo-add gives a defensible insertion
zone. Runtime continues to let the stock engine transfer all ammunition.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import codasset as CA
from extract_geometry import Assets, merge_skeletons, pose_model_space, basis_to_local
from extract_reload import parse_weaponfile


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--main", default=CA.GAME_MAIN)
    parser.add_argument("--guns", required=True)
    parser.add_argument("--reload", required=True)
    parser.add_argument("--out", default="src/vr_reload_insert_zones.inc")
    parser.add_argument("--evidence", default="docs/reload_insert_zones.json")
    args = parser.parse_args()
    with open(args.guns, encoding="utf-8") as stream:
        guns = json.load(stream)["models"]
    with open(args.reload, encoding="utf-8") as stream:
        reloads = {row["weapon"]: row for row in json.load(stream)["weapons"]}
    fs = CA.Pk3Fs(args.main)
    assets = Assets(fs)
    rows = []
    seen = set()
    for gun in guns:
        weapon = next((name for name in gun["weapons"]
                       if name in reloads
                       and reloads[name]["reloadClass"]["value"] in ("MAGAZINE", "INCREMENTAL")), None)
        if not weapon:
            continue
        raw = fs.read("weapons/sp/" + weapon)
        if not raw:
            continue
        fields = parse_weaponfile(raw.decode("latin-1"))
        loop = bool(fields.get("reloadStartAnim") and fields.get("reloadEndAnim"))
        name = fields.get("reloadAnim") if loop else (fields.get("reloadEmptyAnim") or fields.get("reloadAnim"))
        duration = float(fields.get("reloadTime") if loop else (fields.get("reloadEmptyTime") or fields.get("reloadTime")) or 0)
        add = float(fields.get("reloadAddTime") or 0)
        anim = assets.anim(name)
        gun_parts, _ = assets.parts_for(fields.get("gunModel", ""))
        hand_parts, _ = assets.parts_for(fields.get("handModel", ""))
        if not anim or gun_parts is None or hand_parts is None or duration <= 0 or add <= 0 or add > duration:
            continue
        bones, index, anchor = merge_skeletons(hand_parts, gun_parts)
        if anchor is None:
            continue
        frame = min(anim.num_frames - 1, round((anim.num_frames - 1) * add / duration))
        authored_hand = reloads[weapon]["loadHand"]["value"]
        body_index = index.get(gun["bodyBone"].lower())
        hand_index = index.get("bip01 r hand" if authored_hand == "TRIGGER" else "bip01 l hand")
        posed = pose_model_space(bones, [(anim, frame)])
        if body_index not in posed or hand_index not in posed:
            continue
        origin, basis = posed[body_index]
        point = basis_to_local(basis, [posed[hand_index][0][k] - origin[k] for k in range(3)])
        point = [c / 39.3701 for c in point]
        key = gun["vertexCount"]
        record = dict(model=gun["gunModel"], weapon=weapon, vertexCount=key,
                      animation=name, animationSource=fs.source("xanim/" + name),
                      ammoAddTime=add, duration=duration, frame=frame,
                      numFrames=anim.num_frames, authoredHand=authored_hand,
                      loadZoneBodyM=[round(c, 6) for c in point],
                      directLoad=loop or weapon in ("m1garand", "kar98k", "mosin_nagant", "mosin_nagant_sniper"))
        # Scoped/unscoped Kar98 share one body key. Both are receiver loaders;
        # the first profile's transfer point serves the shared receiver.
        if key in seen:
            record["sharedKeyNotEmitted"] = True
        else:
            seen.add(key)
        rows.append(record)
    lines = ["// GENERATED by tools/measure_reload_insert_zones.py.",
             "// Loading hand at the stock ammo-add event in that frame's body-bone metres.",
             "struct ReloadInsertZone { int vertexCount; float pointM[3]; int directLoad; };",
             "static const ReloadInsertZone kReloadInsertZones[] = {"]
    for row in rows:
        if row.get("sharedKeyNotEmitted"):
            continue
        point = row["loadZoneBodyM"]
        lines += ["    // %s: %s frame %d, ammo-add %.3fs / %.3fs" %
                  (row["model"], row["animation"], row["frame"], row["ammoAddTime"], row["duration"]),
                  "    { %d, { %.6ff, %.6ff, %.6ff }, %d }," %
                  (row["vertexCount"], point[0], point[1], point[2], row["directLoad"])]
    lines.append("};")
    with open(args.out, "w", encoding="utf-8") as stream:
        stream.write("\n".join(lines) + "\n")
    with open(args.evidence, "w", encoding="utf-8") as stream:
        json.dump({"method": "authored loading hand at ammo-add normalized reload time, directly in posed body-bone frame", "models": rows}, stream, indent=2)
        stream.write("\n")
    for row in rows:
        print(row["model"], row["loadZoneBodyM"], "receiver" if row["directLoad"] else "magazine")
    print("Wrote", len(seen), "unique measured loading zones")


if __name__ == "__main__":
    main()
