// ----------------------------------------------------------- identification
//
// The runtime never learns a weapon's NAME -- nothing safe exposes it. What it
// does measure every frame is where the viewmodel sits relative to the camera
// (vr_weapon's bakedOffset). Because every weapon's ADS animation starts from
// its own distinct hip pose, that measurement IS a signature, and matching it
// against the offline table names the weapon without reading one byte of
// protected memory.
//
// The catch, stated plainly: whether the measured baked offset equals the
// animation's tag_torso translation is a HYPOTHESIS. It is exactly what the
// next headset run tests. Identification therefore reports a distance and a
// margin, and stays at zero confidence when nothing matches -- which is the
// honest answer if the hypothesis is wrong.

struct VrWeaponMatch {
    int   id;                // best profile id, 0 when nothing matched
    int   runnerUpId;
    float bestDistU;         // distance to the best row, game units
    float runnerUpDistU;
    float marginU;           // runnerUpDist - bestDist
    int   confidence;        // 0..100
    int   usedAdsDelta;      // the sighted pose took part in the score
};

// Score one measurement. hipU is the measured hip-pose offset; when the ADS
// pose has also been observed pass haveAds=1 with the measured sighted offset.
// Returns the best id (0 if none) and fills `out` when non-null.
int VRWProfile_Identify(const float hipU[3], int haveAds, const float adsU[3],
                        VrWeaponMatch* out);

// ------------------------------------------------------------- live tracking
//
// Feed every frame; the module accumulates a stable estimate and only offers
// an identification once the measurement has held still long enough to mean
// something.

