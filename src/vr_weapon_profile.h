struct VrWeaponProfile {
    unsigned short id;                 // table index; 0 = generic fallback
    const char*    name;
    unsigned char  vrClass;            // VRWC_*
    unsigned char  twoHandAllowed;     // VRW2H_*
    unsigned short specialHandling;    // VRWSH_* bits

    // Measured from the shipped ADS animation. CoD units (inches), viewmodel
    // frame: +X forward, +Y left, +Z up, relative to the camera.
    float hipOffsetU[3];
    float sightOffsetU[3];
    int   sightKnown;                  // 0 => both vectors are AUTO

    // Physical grip geometry. No longer "hardware measurement only": most of
    // it is now derived from the weapon's own rig and animations, in METRES
    // and in the WEAPON FRAME (`frameBone` below). Each carries a confidence
    // in conf[] and none of it is hardware-verified.
    float rearGripOffsetM[3];
    float rearGripRotationDeg[3];      // Quake order: pitch, yaw, roll
    float supportAlongAxisM;
    float supportRadiusM;
    float sightForward[3];             // unit, weapon frame

    int   adsAccuracyAllowed;

    // ---- asset-derived geometry (tools/extract_geometry.py) --------------
    // The frame these are expressed in. Usually `tag_weapon`; a few rigs
    // (panzerfaust, m1carbine) never animate it, so their frame is the weapon
    // body bone instead. Recorded rather than assumed because a vector in the
    // wrong frame is worse than no vector.
    const char* frameBone;
    float muzzleOriginM[3];            // muzzle position in the weapon frame
    float barrelForward[3];            // unit bore direction, weapon frame
    float supportOffsetM[3];           // support hand, weapon frame
    float sightOffsetM[3];             // eye relative to the weapon when sighted
    float frameRigidityM;              // how far the body moves in this frame
    unsigned char conf[VRWP_F_COUNT];  // VRWP_CONF_*, indexed by VRWP_F_*
};

// Read an asset-derived value only if its confidence clears the bar. Returns 0
// and leaves `out` untouched otherwise, so a caller that ignores the return
// value gets its own default rather than a WEAK guess.
int VRWProfile_Value3(const VrWeaponProfile* p, int field, float out[3]);
int VRWProfile_Value1(const VrWeaponProfile* p, int field, float* out);

