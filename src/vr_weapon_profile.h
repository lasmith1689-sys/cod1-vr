// Per-weapon VR profiles: what a given CoD1 weapon IS, how it should be held,
// and what the next headset run still has to measure.
//
// WHY A PROFILE LAYER AT ALL
// --------------------------
// The shipped two-handed solver treats every weapon as a rifle. That is right
// for 25 of the 33 carried weapons and wrong for the rest: a Colt does not
// have a forward grip, a grenade has no barrel to steer, an ammo crate has no
// sights, and a mounted MG42 is posed by the engine and must not be touched at
// all. This layer says which is which -- from the game's own data, not from
// guesses.
//
// WHAT IS KNOWN OFFLINE AND WHAT IS NOT
// -------------------------------------
// KNOWN (extracted from the shipped pk3s and regenerated by
// tools/gen_weapon_profiles.py, see src/vr_weapon_profile_table.inc):
//   * class / slot / the game's own `twoHanded` and `aimDownSight` flags
//   * hipOffsetU   -- where the viewmodel sits at hip fire
//   * sightOffsetU -- where it sits with the sights on the eye
//     Both come from the FIRST and LAST keys of the weapon's own ADS_up
//     animation, and the decode is proven by round-tripping ADS_down.
//
// NOT KNOWN, and deliberately left VRWP_AUTO:
//   * rearGripOffset / rearGripRotation -- where a real hand grips the model
//   * supportAlongAxis / supportRadius  -- where the support hand lands
//   * sightForward                      -- the barrel axis in model space
// These are physical facts about a mesh nobody has measured yet. Filling them
// with plausible numbers would look like progress and behave like noise, so
// they stay AUTO and the code falls back to the shipped generic behaviour.
//
// SAFETY POSTURE
// --------------
// The default mode is OBSERVE: identify, score, log -- change nothing. Routing
// only becomes authoritative when the config explicitly asks for it AND the
// identification is confident. An unidentified weapon always resolves to
// profile 0, whose behaviour is byte-for-byte what the deployed candidate
// already does.
