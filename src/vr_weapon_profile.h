// The sentinel for "this number is not known". Chosen far outside any
// physical range so an accidental use is obvious rather than subtle, and
// tested with a threshold rather than equality so a float copy cannot break
// the check.
#define VRWP_AUTO (-1.0e9f)

static inline int VRWP_IsAuto(float v) { return v <= -1.0e8f; }
static inline int VRWP_IsAuto3(const float v[3])
{
    return VRWP_IsAuto(v[0]) || VRWP_IsAuto(v[1]) || VRWP_IsAuto(v[2]);
}

// --------------------------------------------------------------- confidence
//
// A number extracted from the game's own assets is not the same kind of thing
// as a number measured on a headset, and the difference has to survive into
// the runtime or it will quietly get spent as if it were free. So every
// asset-derived value carries how it was arrived at.
//
//   PROVEN  two independent lines of evidence in the assets agree -- e.g. the
//           bore direction from tag_flash's POSITION and from tag_flash's own
//           ROTATION basis and from the weapon body's bounding box
//   STRONG  one authored, named, semantic source, stable across the frames of
//           every animation in which both hands stay on the weapon
//   WEAK    an inference with no named tag behind it, or one the animations
//           contradict
//   NA      the question does not apply to this weapon (a grenade has no
//           barrel; the vestigial tag_flash on its rig is not one)
//   UNKNOWN nothing in the assets answers it -- the value is VRWP_AUTO
//
// None of these means "hardware-verified". That level does not exist yet and
// there is deliberately no enum value for it: the day a headset measurement
// lands, it gets its own.
enum {
    VRWP_CONF_UNKNOWN = 0,
    VRWP_CONF_NA      = 1,
    VRWP_CONF_WEAK    = 2,
    VRWP_CONF_STRONG  = 3,
    VRWP_CONF_PROVEN  = 4
};

