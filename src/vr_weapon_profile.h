// ------------------------------------------------- vr_weapon_debug (phase 7)
//
// The diagnostic that lets ONE two-minute headset run answer "is the model
// calibrated wrong, is the solver wrong, or is gameplay fire lagging?".
//
// DELIBERATELY TELEMETRY, NOT DEBUG PRIMITIVES. Drawing lines for the anchors
// would mean issuing GL inside a renderer this mod already intercepts at the
// projection, viewport, scissor and entity level, during a paired-eye submit
// whose timing is the single most fragile thing in the build. A wrong draw
// call there costs a headset session; a log line costs nothing. When the
// stereo path is settled this can grow a primitive mode -- until then the
// numbers are worth more than the arrows.
//
// It NEVER changes behaviour: it only reads the debug structs the modules
// already publish and formats them.

void VRWDebug_SetEnabled(int on);        // codvr.cfg vr_weapon_debug
int  VRWDebug_Enabled();

// An extra logger appended to every debug block, registered by dllmain. It
// exists because the one thing only dllmain can see -- the raw arguments of
// the entity-add syscalls -- is exactly what the hand-visual work needs, and
// the safe-suite build does not link dllmain. Null (the default) means the
// block simply ends earlier.
typedef void (*VRWDebugExtraFn)();
void VRWDebug_SetExtraLogger(VRWDebugExtraFn fn);
void VRWDebug_SetPeriod(float seconds);  // default 2.0
int  VRWDebug_MaybeLog(double now);      // 1 when a block was emitted
int  VRWDebug_BlocksEmitted();

